"""
Loads the real photographs under datasets/ into (image, label) pairs for the
pavement/road-context classifier.

Ground truth note
------------------
None of the folders under datasets/ come with per-image bounding-box or
per-pixel defect annotations we can trust (the *_CRACK.png / *_POTHOLE.png
files sitting next to each photo are placeholder masks generated by
data/dataset_generator.py, not real annotations - don't train on them).

What IS trustworthy is which curated folder a photo lives in: each one was
hand-picked from a public source that matches its name (RDD2022 potholes,
Kaggle Pothole-600, CRACK500, MoRTH "hard negative" clean-road photos, and a
small set of Wikimedia/Geograph photos for the missing-zebra-crossing /
missing-divider / damaged-sign / waterlogging classes). So we treat the
folder as a weak label - it's a standard "dataset built from curated
directories" approach and it's honest about what the label actually means.

datasets/01_rdd2022_india, 06_astm_d6433_pci_benchmark and
07_monsoon_pavement_deterioration mix several distress types together (their
source datasets aren't single-label), so we don't train on them - they're
held out as an unlabeled sanity-check set instead (see `holdout_images()`).
"""

import os
import re
import glob
import numpy as np
from PIL import Image

_AUG_PREFIX_RE = re.compile(r"^aug_mega_\d+_")

DATASETS_ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "datasets")

# class_id -> (folder name, class name). Folder photos tagged "_RAW" are the
# genuine photos; the augmented "aug_mega_*" copies of them are included too
# since they're still real geometric/photometric transforms of a real photo.
CLASS_FOLDERS = {
    0: ("05_morth_civil_hard_negatives", "Normal Road / Sound Pavement"),
    1: ("03_crack500_fatigue", "Crack (Longitudinal / Transverse / Alligator)"),
    2: ("02_kaggle_pothole_600", "Pothole Cavity"),
    3: ("09_waterlogging_hazard", "Waterlogging / Flooding Hazard"),
    4: ("10_missing_zebra_crossing", "Missing Zebra Crossing"),
    5: ("11_missing_road_divider", "Missing Road Divider"),
    6: ("12_damaged_traffic_signs", "Damaged Traffic Sign"),
}

HOLDOUT_FOLDERS = ["01_rdd2022_india", "06_astm_d6433_pci_benchmark", "07_monsoon_pavement_deterioration"]

CLASS_NAMES = [CLASS_FOLDERS[i][1] for i in sorted(CLASS_FOLDERS)]

_IMG_EXT = (".jpg", ".jpeg", ".png", ".JPG", ".PNG")


def _list_photos(folder, dedupe_augmented=False):
    """
    Lists real photo files in a dataset folder, skipping the synthetic mask
    files (*_CRACK.png, *_POTHOLE.png, *_LANE.png).
    """
    img_dir = os.path.join(DATASETS_ROOT, folder, "real_images")
    if not os.path.isdir(img_dir):
        return []
    files = []
    for path in sorted(glob.glob(os.path.join(img_dir, "*"))):
        name = os.path.basename(path)
        if not name.lower().endswith(_IMG_EXT):
            continue
        if any(tag in name for tag in ("_CRACK.", "_POTHOLE.", "_LANE.")):
            continue
        files.append(path)
    if dedupe_augmented:
        # Keep only one representative per base photo (drop the aug_mega_N
        # copies) - useful when we want a held-out set of distinct scenes.
        seen_base = set()
        unique = []
        for path in files:
            base = _AUG_PREFIX_RE.sub("", os.path.basename(path))
            if base not in seen_base:
                seen_base.add(base)
                unique.append(path)
        files = unique
    return files


def load_image(path, max_side=640):
    """Loads an image file as an RGB uint8 numpy array, downscaled if huge."""
    img = Image.open(path).convert("RGB")
    if max(img.size) > max_side:
        ratio = max_side / float(max(img.size))
        img = img.resize((max(1, int(img.width * ratio)), max(1, int(img.height * ratio))), Image.BILINEAR)
    return np.array(img)


def dataset_inventory():
    """Real counts of usable photos per class + the held-out folders, straight off disk."""
    inv = {}
    for cls_id, (folder, name) in CLASS_FOLDERS.items():
        photos = _list_photos(folder)
        distinct = _list_photos(folder, dedupe_augmented=True)
        inv[name] = {
            "class_id": cls_id,
            "folder": folder,
            "usable_photos": len(photos),
            "distinct_source_photos": len(distinct),
        }
    holdout = {folder: len(_list_photos(folder, dedupe_augmented=True)) for folder in HOLDOUT_FOLDERS}
    return {"labeled_classes": inv, "unlabeled_holdout_folders": holdout}


def load_labeled_dataset(max_per_class=None, dedupe_augmented=False, max_side=640):
    """
    Returns (images, labels, paths) for every class in CLASS_FOLDERS.
    images is a python list of RGB uint8 arrays (sizes vary - caller resizes
    as needed downstream), labels is an int array, paths lines up with both.
    """
    images, labels, paths = [], [], []
    for cls_id, (folder, _name) in CLASS_FOLDERS.items():
        photos = _list_photos(folder, dedupe_augmented=dedupe_augmented)
        if max_per_class is not None:
            photos = photos[:max_per_class]
        for path in photos:
            try:
                images.append(load_image(path, max_side=max_side))
                labels.append(cls_id)
                paths.append(path)
            except Exception:
                continue
    return images, np.array(labels, dtype=np.int64), paths


def sample_photo_path(class_id=None, rng=None):
    """
    Returns one real (path, class_id, class_name) triple, picked at random
    from a labeled class folder - or from all of them if class_id is None.
    Used by demo/UI endpoints that want to show a real labeled example
    instead of fabricating one.
    """
    import random as _random

    rng = rng or _random
    class_ids = [class_id] if class_id is not None and class_id in CLASS_FOLDERS else list(CLASS_FOLDERS.keys())
    candidates = []
    for cid in class_ids:
        folder, name = CLASS_FOLDERS[cid]
        for path in _list_photos(folder, dedupe_augmented=True):
            candidates.append((path, cid, name))
    if not candidates:
        return None
    return rng.choice(candidates)


def holdout_images(max_side=640):
    """Real photos from the mixed-label folders, for qualitative spot checks only (no trustworthy label)."""
    out = []
    for folder in HOLDOUT_FOLDERS:
        for path in _list_photos(folder, dedupe_augmented=True):
            try:
                out.append((path, load_image(path, max_side=max_side)))
            except Exception:
                continue
    return out
